import '../../domain/entities/transaction.dart';

/// Fixed reference point for all sample timestamps. Using a constant instead
/// of `DateTime.now()` keeps the data, and therefore every test, deterministic.
final DateTime _base = DateTime.utc(2026, 10, 20, 18);

Transaction _transaction(
  String id,
  String merchantName,
  int amountMinor,
  String currencyCode,
  TransactionStatus status,
  Duration age, {
  String? reference,
}) {
  return Transaction(
    id: id,
    merchantName: merchantName,
    amountMinor: amountMinor,
    currencyCode: currencyCode,
    status: status,
    createdAt: _base.subtract(age),
    reference: reference,
  );
}

